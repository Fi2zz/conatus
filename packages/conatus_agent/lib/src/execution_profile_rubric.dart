// REASON: 静态提示词常量，不是逻辑；集中一处便于评审与本地化。
/// 档位选择的提示词：只用任务文本里的证据，禁止使用历史结果。
library;

/// 一次 tool-free 小调用使用的 rubric。
///
/// 结构取自 HarnessPro 的 `profile_rubric.md`：档位定义 + 证据规则 + 按序门控。
/// 阈值属于本项目自己的标定，不与论文数字对齐。
const String kExecutionProfileRubric = '''
你要为一次 Agent 任务选择执行档位。只输出一个档位名（compact / lean /
standard / deep / research），不要输出解释、标点或其它文字。

档位：
- compact：低推理；约 2 次调用后进入经济阶段，4 次后收敛，14 次内收口。
- lean：低推理；约 6 次后经济，10 次后收敛，22 次内收口。
- standard：中推理；约 14 次后经济，26 次后收敛，44 次内收口。
- deep：高推理；约 16 次后经济，30 次后收敛，54 次内收口。
- research：高推理；约 8 次后经济，20 次后收敛，46 次内收口。

证据规则：
- 只使用任务文本里显式描述的验证方式、交互方式、依赖、产物与约束。
- 禁止使用历史结果、先前评测分数、记忆中的类似任务或隐藏测试的假设。
- 未描述的验证器等于质量未知，不等于质量弱；信息不足时默认 standard。
- 只有显式、本地、可重复，并能给出定位失败、量化误差、候选排序、确定性模拟
  或可直接检视目标的验证，才算强 oracle。
- 统计的是「能被证据区分开的假设数」，不是文件数、命令数或重试次数。
- 把任务给的时间上限与单次探测成本算进迭代价值。

按序判断，命中即停：

第 1 关 compact：明确存在下列之一时才选——
1. 长时间串行的图形、远程、虚拟化或人工交互，正确性依赖视觉或隐藏状态；
2. 账号、设备、服务、凭据或外部状态不可用，且无忠实本地替代；
3. 大范围隐藏或事实上无界的行为，同时要求精确保留无关细节，反馈只有端到端
   接受/拒绝；
4. 同一份产物必须同时满足多个独立语法、解析器、运行时或环境，而检查只暴露
   联合的接受/拒绝；
5. 大批量媒体或视觉理解，没有描述数值比较方式，正确性依赖视觉判断。
仅「困难」「需要可视化」「需要虚拟化」不足以选 compact。

第 2 关 research：主要交付物是事实重建，需要多个可访问来源、版本/日期对齐、
出处或历史快照时才选。决定性来源不可访问时改选 compact。

第 3 关 deep：任务显式描述或可从确定性参考、变换、模拟器、运行时构造出强本地
oracle，且至少满足下列一种形态——
1. 恢复潜在结构或参数，并有精确兼容性或量化目标；
2. 正确性跨多个相互作用的组件、阶段或状态，可用精确不变式、参考行为或往返
   检查；
3. 恢复受损的结构化状态，存在相互竞争的格式、顺序或变换假设；
4. 受约束的合成、压缩、瘦身或候选搜索，且硬约束耦合、有可执行评分器；
5. 从大量观测中做非平凡恢复、推断或攻击，并能精确验证候选；
6. 有确定性模拟器或量化目标的逆问题；
7. 针对确定性变换或运行时构造候选，存在多个可执行、可观测且实质不同的机制；
8. 在语言、体积、兼容性或依赖受限下重实现确定性参考行为，候选输出可在本地
   精确比对；
9. 同一份源产物必须同时满足两个以上独立语法、编译器或运行时，且每个都能单独
   执行以获得定位反馈。
术语、长规格、普通安全或逆向、仅有隐藏测试，都不足以选 deep。普通性能调优与
普通的状态传播属于 standard。每次候选评估都昂贵、工作主要是针对一个给定评分器
做有界调参时，优先 standard。

第 4 关 lean：下列全部成立时才选——
1. 有界、基本确定的工作；
2. 至多两个有意义的不确定性；
3. 在广泛探索前就有可信计划；
4. 有一个覆盖几乎全部决定性行为的本地直接检查；
5. 检查、实现与最终验证合计约八次以内能产生证据的调用。

第 5 关 standard：其余情况一律 standard，包括 oracle 质量未知。它是普通实现、
调试、数据处理、服务搭建、有界数值工作与多不确定分析的默认档。

若证据不足或任务文本异常，输出 standard。''';
